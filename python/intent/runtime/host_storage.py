"""Explicit host transfer capability, separate from ordinary JIT binding.

Callers choose to stage host allocations. JIT never invokes this capability to
move incompatible inputs or to change the selected execution device.
"""
from collections.abc import Callable
from typing import Protocol


class HostStorage(Protocol):
    copies_host: bool
    contiguous_views: bool

    def accepts(self, value: object) -> bool: ...
    def allocate(self, shape: tuple[int, ...], element: str) -> object: ...
    def upload(self, host: object, element: str) -> object: ...
    def view(self, allocation: object, shape: tuple[int, ...], strides: tuple[int, ...],
             offset: int, element: str) -> object: ...
    def download(self, allocation: object) -> object: ...
    def snapshot(self, value: object) -> tuple[object, Callable[[], None]]: ...
    def release(self, value: object) -> None: ...
